// Read-only documentation review. This does not install an app MCP endpoint.
import { mkdir, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
const output = new URL("../.test-data/nuxt-mcp-review/", import.meta.url);
const evidence = new URL("../docs/nuxt-review/", import.meta.url);
await mkdir(output, { recursive: true });
await mkdir(evidence, { recursive: true });
const documentation = await fetch("https://nuxt.com/docs/3.x/guide/ai/mcp", {
  headers: { Accept: "text/markdown" },
  signal: AbortSignal.timeout(20000),
});
const page = await documentation.text();
const urls = [...new Set(page.match(/https[^\s<>"\\]+/g) || [])].filter((url) =>
  url.includes("mcp"),
);
console.log(
  JSON.stringify(
    {
      status: documentation.status,
      contentType: documentation.headers.get("content-type"),
      urls,
    },
    null,
    2,
  ),
);
await writeFile(new URL("mcp-discovery.txt", output), page);
const endpoint = "https://nuxt.com/mcp";
let id = 0;
let session;
async function rpc(method, params, notify = false) {
  const response = await fetch(endpoint, {
    method: "POST",
    headers: {
      "Content-Type": "application/json",
      Accept: "application/json, text/event-stream",
      ...(session ? { "Mcp-Session-Id": session } : {}),
    },
    body: JSON.stringify({
      jsonrpc: "2.0",
      ...(notify ? {} : { id: ++id }),
      method,
      params,
    }),
    signal: AbortSignal.timeout(30000),
  });
  session ||= response.headers.get("mcp-session-id");
  const text = await response.text();
  if (!response.ok)
    throw new Error(`${method}: HTTP ${response.status}: ${text}`);
  if (!text) return null;
  const result = response.headers
    .get("content-type")
    ?.includes("text/event-stream")
    ? JSON.parse(
        text
          .split("\n")
          .filter((line) => line.startsWith("data:"))
          .map((line) => line.slice(5).trim())
          .join("\n"),
      )
    : JSON.parse(text);
  if (result.error) throw new Error(JSON.stringify(result.error));
  return result;
}
const initialize = await rpc("initialize", {
  protocolVersion: "2025-03-26",
  capabilities: {},
  clientInfo: { name: "lyra-nuxt-review", version: "1.0.0" },
});
await rpc("notifications/initialized", {}, true);
const listing = await rpc("tools/list", {});
await writeFile(
  new URL("mcp-tools.json", output),
  JSON.stringify(
    { accessedAt: new Date().toISOString(), endpoint, initialize, listing },
    null,
    2,
  ),
);
console.log(
  "Available tools:",
  listing.result.tools.map((tool) => tool.name).join(", "),
);
const calls = [
  {
    name: "list-documentation-pages",
    arguments: { version: "3.x", search: "data fetching" },
  },
  {
    name: "get-documentation-page",
    arguments: { path: "/docs/3.x/api/composables/use-lazy-fetch" },
  },
  {
    name: "get-documentation-page",
    arguments: { path: "/docs/3.x/api/composables/use-fetch" },
  },
  {
    name: "get-documentation-page",
    arguments: { path: "/docs/3.x/api/composables/use-async-data" },
  },
  {
    name: "get-documentation-page",
    arguments: { path: "/docs/3.x/api/composables/use-request-fetch" },
  },
  {
    name: "get-documentation-page",
    arguments: { path: "/docs/3.x/guide/best-practices/hydration" },
  },
  {
    name: "get-documentation-page",
    arguments: { path: "/docs/3.x/guide/going-further/runtime-config" },
  },
];
const results = [];
for (const call of calls) {
  const response = await rpc("tools/call", call);
  results.push({ call, response });
  console.log(
    `${call.name} ${JSON.stringify(call.arguments)}: ${response.result?.isError ? "error" : "ok"}`,
  );
}
await writeFile(
  new URL("mcp-calls.json", output),
  JSON.stringify(
    { accessedAt: new Date().toISOString(), endpoint, results },
    null,
    2,
  ),
);
await writeFile(
  new URL("mcp-evidence.json", evidence),
  JSON.stringify(
    {
      accessedAt: new Date().toISOString(),
      endpoint,
      discovery: "https://nuxt.com/docs/3.x/guide/ai/mcp",
      transport:
        "JSON-RPC 2.0 over HTTPS, initialize + notifications/initialized + tools/list + tools/call",
      initialize: initialize.result,
      availableTools: listing.result.tools.map((tool) => tool.name),
      calls: results.map(({ call, response }) => {
        const text = response.result.content
          .filter((block) => block.type === "text")
          .map((block) => block.text)
          .join("\n");
        return {
          ...call,
          success: !response.result.isError,
          resultId: response.id,
          returnedCharacters: text.length,
          sha256: createHash("sha256").update(text).digest("hex"),
        };
      }),
      rawResponses:
        ".test-data/nuxt-mcp-review/ (ignored; regenerated by this script)",
    },
    null,
    2,
  ),
);
