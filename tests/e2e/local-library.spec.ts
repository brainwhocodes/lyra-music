import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { audit, credentials, guard, login, navigate } from './helpers';
import { playbackPosition, pointerSeek, positionValue, seekSeconds } from './player-controls';
import { originalStreamEvidence } from './stream-evidence';

test('login rejects invalid credentials and supports registration navigation and keyboard submission', async ({ page }, info) => {
  const errors = guard(page, [{ path: '/api/auth/login', status: 401 }]);
  await page.goto('/login');
  if (process.env.LYRA_E2E_DEV === '1') await page.waitForLoadState('networkidle');
  await audit(page, info, 'login');
  await page.getByRole('link', { name: 'Register', exact: true }).click();
  await expect(page).toHaveURL(/\/register$/);
  await audit(page, info, 'registration');
  await page.getByRole('link', { name: 'Login', exact: true }).click();
  await expect(page).toHaveURL(/\/login$/);
  await page.getByLabel('Email', { exact: true }).fill(credentials.email);
  await page.getByLabel('Password', { exact: true }).fill('short');
  await page.getByRole('button', { name: 'Login', exact: true }).click();
  await expect(page.getByText('Password must be at least 8 characters', { exact: true })).toBeVisible();
  await page.getByLabel('Password', { exact: true }).fill('IncorrectPassword123!');
  const rejected = page.waitForResponse((response) => response.url().endsWith('/api/auth/login') && response.status() === 401);
  await page.getByRole('button', { name: 'Login', exact: true }).click();
  await rejected;
  await expect(page.getByText('Invalid email or password', { exact: true })).toBeVisible();
  await expect(page).toHaveURL(/\/login$/);
  expect((await page.context().cookies()).find((cookie) => cookie.name === 'auth_token')).toBeUndefined();
  await page.getByLabel('Password', { exact: true }).fill(credentials.password);
  await page.getByRole('button', { name: 'Show password', exact: true }).click();
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'text');
  await expect(page.getByLabel('Password', { exact: true })).toHaveValue(credentials.password);
  await page.getByRole('button', { name: 'Hide password', exact: true }).click();
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'password');
  await expect(page.getByLabel('Password', { exact: true })).toHaveValue(credentials.password);
  await page.getByRole('button', { name: 'Login', exact: true }).focus();
  await page.keyboard.press('Enter');
  await expect(page).toHaveURL(/\/library$/);
  expect(errors).toEqual([]);
});

test('search finds a real album and playback decodes its licensed audio', async ({ page, isMobile }, info) => {
  const errors = guard(page);
  const streams = originalStreamEvidence(page);
  await login(page);
  await audit(page, info, 'library');
  await page.getByRole('textbox', { name: 'Search library' }).fill('Mono');
  await expect(page.getByRole('region', { name: 'Library search results' }).getByRole('link', { name: 'Monomyth', exact: true })).toBeVisible();
  await audit(page, info, 'search-results');
  await page.getByRole('region', { name: 'Library search results' }).getByRole('link', { name: 'Monomyth', exact: true }).click();
  await expect(page).toHaveURL(/\/albums\/album-the-distant-sun$/);
  await expect(page.getByRole('heading', { name: 'Monomyth', exact: true })).toBeVisible();
  const track = page.getByRole('row', { name: /The Distant Sun/ });
  await expect(track).toHaveCount(1);
  const stream = page.waitForResponse((response) => /\/api\/tracks\/the-distant-sun\/play/.test(response.url()) && response.ok());
  await track.click();
  expect((await stream).headers()['content-type']).toContain('audio/');
  await expect(page.getByRole('button', { name: 'Pause playback', exact: true })).toBeVisible();
  if (isMobile) {
    await page.getByRole('button', { name: /^Open full screen player:/ }).click();
    await expect(page.getByRole('heading', { name: 'The Distant Sun', exact: true })).toBeVisible();
  }
  const playback = isMobile ? page.getByRole('dialog', { name: 'The Distant Sun', exact: true }) : page.getByRole('region', { name: 'Music player', exact: true });
  await expect.poll(() => positionValue(playbackPosition(playback))).toBeGreaterThan(0);
  await playback.getByRole('button', { name: 'Pause playback', exact: true }).click();
  await expect(playback.getByRole('button', { name: 'Play playback', exact: true })).toBeVisible();
  await pointerSeek(playback, 0.5);
  await seekSeconds(playback, 5);
  await streams.complete('the-distant-sun', playback);
  const volume = playback.getByRole('button', { name: 'Volume', exact: true });
  await volume.click();
  await expect(volume).toHaveAttribute('aria-expanded', 'true');
  const level = playback.getByRole('slider', { name: 'Volume level', exact: true });
  await level.focus();
  await level.press('Home');
  for (let step = 0; step < 20; step++) await level.press('ArrowRight');
  await expect(level).toHaveValue('20');
  await playback.getByRole('button', { name: 'Mute', exact: true }).click();
  await expect(level).toHaveValue('0');
  await page.keyboard.press('Escape');
  await expect(volume).toBeFocused();
  await expect(volume).toHaveAttribute('aria-expanded', 'false');
  if (!isMobile) await page.getByRole('button', { name: /^Open full screen player:/ }).click();
  const fullPlayer = page.getByRole('dialog', { name: 'The Distant Sun', exact: true });
  const fullVolume = fullPlayer.getByRole('button', { name: 'Volume', exact: true });
  await fullVolume.click();
  const fullLevel = fullPlayer.getByRole('slider', { name: 'Volume level', exact: true });
  await expect(fullLevel).toHaveValue('0');
  await fullPlayer.getByRole('button', { name: 'Unmute', exact: true }).click();
  await expect(fullLevel).toHaveValue('20'); // Shared remembered volume across player instances.
  await fullLevel.focus();
  await fullLevel.press('End');
  await expect(fullLevel).toHaveValue('100');
  await fullLevel.press('ArrowLeft');
  await expect(fullLevel).toHaveValue('99');
  await fullLevel.press('Home');
  await expect(fullLevel).toHaveValue('0');
  await fullPlayer.getByRole('button', { name: 'Unmute', exact: true }).click();
  await expect(fullLevel).toHaveValue('99');
  await fullLevel.press('End');
  await expect(fullLevel).toHaveValue('100');
  await audit(page, info, 'player-volume-popover');
  await page.keyboard.press('Escape');
  await expect(fullVolume).toBeFocused();
  await expect(fullVolume).toHaveAttribute('aria-expanded', 'false');
  await expect(playbackPosition(fullPlayer)).toHaveValue('5');
  if (!isMobile) await fullPlayer.getByRole('button', { name: 'Close full screen player', exact: true }).click();
  if (!isMobile) {
    await page.getByRole('button', { name: 'Up Next', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Up Next', exact: true })).toBeVisible();
    await audit(page, info, 'queue');
    await page.getByRole('button', { name: 'Up Next', exact: true }).click();
    await expect(page.getByRole('heading', { name: 'Up Next', exact: true })).toHaveCount(0);
    await page.getByRole('button', { name: 'Repeat mode: none', exact: true }).click();
    await expect(page.getByRole('button', { name: 'Repeat mode: all', exact: true })).toBeVisible();
  } else {
    await audit(page, info, 'full-screen-player');
    await page.getByRole('button', { name: 'Close full screen player' }).click();
    await expect(page.getByRole('button', { name: 'Play playback', exact: true })).toBeVisible();
  }
  await page.getByRole('button', { name: 'Play playback', exact: true }).focus();
  await page.keyboard.press('Space');
  await expect(page.getByRole('button', { name: 'Pause playback', exact: true })).toBeVisible();
  await audit(page, info, 'album-playing');
  streams.assertClean(errors, { 'the-distant-sun': 1 });
});

test('album navigation and filtering show populated and empty library states', async ({ page, isMobile }, info) => {
  const errors = guard(page);
  await login(page);
  await navigate(page, 'Albums', isMobile);
  await expect(page.getByRole('heading', { name: /^(Monomyth|Library Songs 5)$/ })).toHaveCount(2);
  const search = page.getByRole('searchbox', { name: 'Search albums', exact: true });
  await search.fill('No such licensed album');
  await expect(page.getByText('No albums found matching your search.', { exact: true })).toBeVisible();
  await search.fill('Scott');
  await expect(page.getByRole('heading', { name: /^(Monomyth|Library Songs 5)$/ })).toHaveCount(2);
  await audit(page, info, 'albums');
  await page.getByRole('heading', { name: 'Library Songs 5', exact: true }).click();
  await expect(page).toHaveURL(/\/albums\/album-signal-to-noise$/);
  await expect(page.getByRole('row', { name: /Signal to Noise/ })).toHaveCount(1);
  expect(errors).toEqual([]);
});

test('playlist creation supports cancellation, Escape, validation, search and persistence', async ({ page, isMobile }, info) => {
  const errors = guard(page, [{ path: '/api/playlists', status: 409 }]);
  await login(page);
  await navigate(page, 'Playlists', isMobile);
  await page.getByRole('button', { name: 'New Playlist', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Create New Playlist' });
  await expect(dialog).toBeVisible();
  await expect(dialog.getByRole('button', { name: 'Create', exact: true })).toBeDisabled();
  await dialog.getByLabel('Playlist Name', { exact: true }).fill('   ');
  await expect(dialog.getByRole('button', { name: 'Create', exact: true })).toBeDisabled();
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: 'New Playlist', exact: true }).click();
  await dialog.getByRole('button', { name: 'Close create playlist' }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: 'New Playlist', exact: true }).click();
  await expect(dialog.getByLabel('Playlist Name', { exact: true })).toBeFocused().catch(async (error) => {
    await info.attach('dialog-focus-state', { body: JSON.stringify(await page.evaluate(() => ({ active: document.activeElement?.outerHTML.slice(0, 300), documentFocused: document.hasFocus(), dialogs: [...document.querySelectorAll('dialog')].map((element) => ({ open: element.open, modal: element.matches(':modal'), visibility: getComputedStyle(element).visibility, html: element.outerHTML.slice(0, 150), inputs: [...element.querySelectorAll('input')].map((input) => ({ visibility: getComputedStyle(input).visibility, disabled: input.disabled, tabIndex: input.tabIndex, inert: input.closest('[inert]')?.tagName })) })) }))), contentType: 'application/json' });
    throw error;
  });
  await page.keyboard.press('Tab');
  await expect(dialog.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(dialog.getByLabel('Playlist Name', { exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('button', { name: 'New Playlist', exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'New Playlist', exact: true }).click();
  const name = `Licensed listening ${info.project.name}`;
  await dialog.getByLabel('Playlist Name', { exact: true }).fill(name);
  const accessibility = await new AxeBuilder({ page }).include('[aria-labelledby="create-playlist-heading"]').analyze();
  await info.attach('playlist-dialog-axe', { body: JSON.stringify(accessibility.violations, null, 2), contentType: 'application/json' });
  expect(accessibility.violations.filter((violation) => ['serious', 'critical'].includes(violation.impact ?? ''))).toEqual([]);
  await audit(page, info, 'playlist-dialog');
  await dialog.getByRole('button', { name: 'Create', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
  await page.reload();
  if (process.env.LYRA_E2E_DEV === '1') await page.waitForLoadState('networkidle');
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
  await page.getByRole('searchbox', { name: 'Search playlists', exact: true }).fill('absent playlist');
  await expect(page.getByRole('heading', { name, exact: true })).toHaveCount(0);
  await page.getByRole('searchbox', { name: 'Search playlists', exact: true }).fill(name);
  await expect(page.getByRole('heading', { name, exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'New Playlist', exact: true }).click();
  await dialog.getByLabel('Playlist Name', { exact: true }).fill(name);
  await dialog.getByRole('button', { name: 'Create', exact: true }).click();
  await expect(dialog.getByRole('alert')).toHaveText('A playlist with this name already exists');
  await expect(dialog.getByRole('button', { name: 'Create', exact: true })).toBeEnabled();
  await dialog.getByLabel('Playlist Name', { exact: true }).fill(`${name} retry`);
  await dialog.getByRole('button', { name: 'Create', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('heading', { name: `${name} retry`, exact: true })).toBeVisible();
  await audit(page, info, 'playlists');
  expect(errors).toEqual([]);
});
