test('settings can browse, add, scan and remove an isolated empty music folder', async ({ page }, info) => {
  const errors = guard(page);
  const directory = await mkdtemp(join(tmpdir(), 'lyra-settings-e2e-'));
  try {
    await login(page);
    await navigate(page, 'Settings');
    const listingResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/filesystem/browse' && response.request().method() === 'GET');
    await page.getByRole('button', { name: 'Browse', exact: true }).click();
    const browser = page.getByRole('dialog', { name: 'Browse for Folder', exact: true });
    await expect(browser).toBeVisible();
    const listed = await listingResponse;
    expect(listed.ok()).toBe(true);
    const listing = await listed.json();
    expect(listing.currentPath).toBeTruthy();
    expect(Array.isArray(listing.entries)).toBe(true);
    await expect(browser.getByText('Current path: ' + listing.currentPath, { exact: true })).toBeVisible();
    await expect(browser.getByText('Loading folders…', { exact: true })).toHaveCount(0);
    await expect(browser.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused();
    await audit(page, info, 'settings-folder-browser');
    await page.keyboard.press('Escape');
    await expect(browser).not.toBeVisible();
    await expect(page.getByRole('button', { name: 'Browse', exact: true })).toBeFocused();
    await page.getByLabel('Folder path', { exact: true }).fill(directory);
    await page.getByRole('button', { name: 'Add Folder', exact: true }).click();
    await expect(page.getByText('Folder added. Scan your folders to update the library.', { exact: true })).toBeVisible();
    await page.reload();
    await expect(page.getByRole('button', { name: 'Remove folder ' + directory, exact: true })).toBeVisible();
    const queued = page.waitForResponse(response => response.url().endsWith('/api/settings/scan') && response.request().method() === 'POST');
    await page.getByRole('button', { name: 'Scan All Folders', exact: true }).click();
    const response = await queued;
    expect(response.status()).toBe(202);
    const body = await response.json();
    expect(body.scans).toHaveLength(1);
    await expect(page.getByText('Queued 1 scan job(s).', { exact: true })).toBeVisible();
    // This server deliberately runs without the separate scan-worker process.
    // Assert the actual queue contract and cancel the pending job before cleanup.
    const status = await page.request.get('/api/scan/status', { params: { scanId: body.scans[0].scanId } });
    expect(status.ok()).toBe(true);
    expect((await status.json()).state).toBe('queued');
    const cancel = await page.request.post('/api/scan/cancel', { data: { scanId: body.scans[0].scanId } });
    expect(cancel.ok()).toBe(true);
    expect((await cancel.json()).cancelled).toBe(true);
    await audit(page, info, 'settings-scan-queued');
    await checkAccessibility(page, info, 'settings-scan-queued');
    await checkLayout(page);
    await page.getByRole('button', { name: 'Remove folder ' + directory, exact: true }).click();
    const remove = page.getByRole('dialog', { name: 'Remove media folder', exact: true });
    await remove.getByRole('button', { name: 'Cancel', exact: true }).click();
    await expect(remove).not.toBeVisible();
    await page.getByRole('button', { name: 'Remove folder ' + directory, exact: true }).click();
    await audit(page, info, 'settings-remove-folder');
    await remove.getByRole('button', { name: 'Remove folder', exact: true }).click();
    await expect(remove).not.toBeVisible();
    await expect(page.getByText('No media folders added yet.', { exact: true })).toBeVisible();
    expect(errors).toEqual([]);
  } finally {
    // Verify the resolved deletion target is precisely this task's mkdtemp child.
    if (dirname(resolve(directory)) !== resolve(tmpdir()) || !directory.includes('lyra-settings-e2e-')) throw new Error('Unexpected temporary fixture path');
    await rm(directory, { recursive: true, force: true });
  }
});
