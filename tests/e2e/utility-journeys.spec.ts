test('podcast RSS subscription, feed refresh, audio playback and unsubscribe use a real local publisher', async ({ page }, info) => {
  const errors = guard(page);
  const analysisRequests: string[] = [];
  const musicHistoryRequests: string[] = [];
  page.on('request', request => {
    const path = new URL(request.url()).pathname;
    if (/\/api\/tracks\/[^/]+\/stream$/.test(path)) analysisRequests.push(request.url());
    if (path === '/api/plays') musicHistoryRequests.push(request.url());
  });
  await login(page);
  await navigate(page, 'Podcasts');
  await expect(page.getByRole('button', { name: 'Subscribe', exact: true })).toBeDisabled();
  await page.getByLabel('RSS feed URL', { exact: true }).fill('http://127.0.0.1:3101/second-feed.xml');
  await page.getByRole('button', { name: 'Subscribe', exact: true }).click();
  await expect(page.getByText('Podcast added to your subscriptions.', { exact: true })).toBeVisible();
  await audit(page, info, 'podcasts-subscribed');
  await page.getByRole('link', { name: 'Field Notes', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Field Notes', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'A quieter morning', exact: true })).toBeVisible();
  const feed = page.waitForResponse(response => /\/api\/podcasts\/[^/]+\/episodes$/.test(response.url()) && response.ok());
  await page.getByRole('button', { name: 'Update feed', exact: true }).click();
  await feed;
  const audio = page.waitForResponse(response => response.url() === 'http://127.0.0.1:3101/episode.mp3' && response.ok());
  await page.getByRole('button', { name: 'Play latest episode', exact: true }).click();
  expect((await audio).headers()['content-type']).toContain('audio/');
  const fullPlayer = page.getByRole('button', { name: /^Open full screen player:/ });
  const narrowPlayer = await fullPlayer.isVisible();
  if (narrowPlayer) await fullPlayer.click();
  const playback = narrowPlayer ? page.getByRole('dialog', { name: 'A quieter morning', exact: true }) : page.getByRole('region', { name: 'Music player', exact: true });
  await expect.poll(() => positionValue(playbackPosition(playback))).toBeGreaterThan(0);
  await playback.getByRole('button', { name: 'Pause playback', exact: true }).click();
  await expect(playback.locator('svg[aria-label="Track waveform"]')).toHaveCount(0);
  await pointerSeek(playback, 0.5);
  // Cross the music-history threshold through real native input. External
  // episodes must never be submitted as synthetic IDs to the music table.
  await seekSeconds(playback, 7);
  await seekSeconds(playback, 3);
  await expect(playback.getByRole('button', { name: 'Play playback', exact: true })).toBeEnabled();
  await audit(page, info, 'podcast-plain-seek');
  await checkAccessibility(page, info, 'podcast-plain-seek');
  expect(analysisRequests).toEqual([]);
  const close = page.getByRole('button', { name: 'Close full screen player', exact: true });
  if (await close.isVisible()) await close.click();
  await audit(page, info, 'podcast-detail');
  await checkAccessibility(page, info, 'podcast-detail');
  await checkLayout(page);
  await page.getByRole('button', { name: 'Unsubscribe', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Unsubscribe from podcast?', exact: true });
  await expect(dialog.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(dialog).not.toBeVisible();
  await page.getByRole('button', { name: 'Unsubscribe', exact: true }).click();
  await audit(page, info, 'podcast-unsubscribe');
  await dialog.getByRole('button', { name: 'Unsubscribe', exact: true }).click();
  await expect(page).toHaveURL(/\/podcasts$/);
  await expect(page.getByRole('link', { name: 'Field Notes', exact: true })).toHaveCount(0);
  await expect(page.getByRole('link', { name: 'Listening Notes', exact: true })).toBeVisible();
  expect(musicHistoryRequests).toEqual([]);
  expect(errors).toEqual([]);
});

