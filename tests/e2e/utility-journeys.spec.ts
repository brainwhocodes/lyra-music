async function expectRadioAudioProgress(page: Page) {
  const trigger = page.getByRole('button', { name: /^Open full screen player:/ });
  const compact = await trigger.isVisible();
  if (compact) await trigger.click();
  const player = compact
    ? page.getByRole('dialog', { name: /^(The Distant Sun|Signal to Noise)$/ })
    : page.getByRole('region', { name: 'Music player', exact: true });
  const progress = playbackPosition(player);
  await expect(progress).toBeVisible();
  const initial = await positionValue(progress);
  await expect.poll(() => positionValue(progress)).toBeGreaterThan(initial + 0.1);
  if (compact) await player.getByRole('button', { name: 'Close full screen player', exact: true }).click();
}

