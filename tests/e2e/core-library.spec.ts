import { test, expect } from '@playwright/test';
import { audit, checkAccessibility, checkLayout, guard, login, navigate } from './helpers';
import { originalStreamEvidence } from './stream-evidence';

test('album views, sorting, menu keyboard behavior and playlist selection stay usable', async ({ page }, info) => {
  const errors = guard(page);
  await login(page);
  await navigate(page, 'Albums');
  await page.getByRole('combobox', { name: 'Sort albums' }).selectOption('year');
  await expect(page.getByRole('combobox', { name: 'Sort albums' })).toHaveValue('year');
  await page.getByRole('button', { name: 'List view', exact: true }).click();
  await expect(page.getByRole('button', { name: 'List view', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await checkLayout(page);
  await audit(page, info, 'albums-list');
  await page.getByRole('button', { name: 'Grid view', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Grid view', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.getByRole('link', { name: 'Monomyth', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Monomyth', exact: true })).toBeVisible();
  const row = page.getByRole('row', { name: /The Distant Sun/ });
  const options = row.getByRole('button', { name: 'Open options menu' });
  await options.focus();
  await page.keyboard.press('Enter');
  await expect(page.getByRole('button', { name: 'Edit Track', exact: true })).toBeVisible();
  await audit(page, info, 'track-options');
  await page.keyboard.press('Escape');
  await expect(page.getByRole('button', { name: 'Edit Track', exact: true })).toHaveCount(0);
  await expect(options).toBeFocused();
  await page.keyboard.press('Enter');
  await page.getByRole('button', { name: 'Add to Playlist', exact: true }).click();
  const trackPicker = page.getByRole('dialog', { name: 'Add The Distant Sun to playlist', exact: true });
  await expect(trackPicker).toBeVisible();
  await expect(page.getByRole('button', { name: 'Edit Track', exact: true })).toHaveCount(0);
  // Cancel remains mounted while async playlist choices load, preserving focus.
  await expect(trackPicker.getByRole('button', { name: 'Cancel', exact: true })).toBeFocused();
  await expect(trackPicker.getByRole('button', { name: 'Local listening', exact: true })).toBeVisible();
  // The preceding keyboard target is the final choice, whose data can change
  // as other journeys create playlists. Position is the behavior under test.
  const pickerButtons = trackPicker.getByRole('button');
  await page.keyboard.press('Shift+Tab');
  await expect(pickerButtons.nth(await pickerButtons.count() - 2)).toBeFocused();
  await audit(page, info, 'track-playlist-picker');
  await page.keyboard.press('Escape');
  await expect(trackPicker).not.toBeVisible();
  await page.getByRole('button', { name: 'Add to playlist', exact: true }).click();
  const picker = page.getByRole('dialog', { name: 'Add Monomyth to playlist', exact: true });
  await expect(picker).toBeVisible();
  await audit(page, info, 'album-playlist-picker');
  await checkAccessibility(page, info, 'album-playlist-picker');
  await picker.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(picker).not.toBeVisible();
  await page.getByRole('button', { name: 'Add to playlist', exact: true }).click();
  await picker.getByRole('button', { name: 'Local listening', exact: true }).click();
  await expect(picker).not.toBeVisible();
  await expect(page.getByText('Album "Monomyth" added to playlist.', { exact: true })).toBeVisible();
  await row.getByRole('link', { name: 'Scott Buckley', exact: true }).click();
  await expect(page).toHaveURL(/\/artists\/scott-buckley$/);
  await expect(page.getByRole('button', { name: 'Pause playback', exact: true })).toHaveCount(0);
  await expect(page.getByRole('heading', { name: 'Scott Buckley', exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

test('artist, genre and track discovery filters navigate and play real local tracks', async ({ page }, info) => {
  const errors = guard(page);
  const streams = originalStreamEvidence(page);
  await login(page);
  await navigate(page, 'Artists');
  const artistSearch = page.getByRole('searchbox', { name: 'Search artists' });
  await artistSearch.fill('No matching artist');
  await expect(page.getByText('No artists match your search.', { exact: true })).toBeVisible();
  await artistSearch.fill('Scott');
  await page.getByRole('combobox', { name: 'Sort artists' }).selectOption('desc');
  await expect(page.getByRole('combobox', { name: 'Sort artists' })).toHaveValue('desc');
  await audit(page, info, 'artists-filtered');
  await page.getByRole('link', { name: /^Scott Buckley/ }).click();
  await expect(page).toHaveURL(/\/artists\/scott-buckley$/);
  await expect(page.getByRole('heading', { name: /^(The Distant Sun|Signal to Noise)$/, level: 3 })).toHaveCount(2);
  const play = page.getByRole('button', { name: 'Play The Distant Sun', exact: true });
  await play.focus();
  const audio = page.waitForResponse(response => /\/api\/tracks\/the-distant-sun\/play/.test(response.url()) && response.ok());
  await page.keyboard.press('Enter');
  expect((await audio).headers()['content-type']).toContain('audio/');
  await expect(page.getByRole('button', { name: 'Pause The Distant Sun', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Pause The Distant Sun', exact: true }).click();
  const player = page.getByRole('region', { name: 'Music player', exact: true });
  await streams.complete('the-distant-sun', player);
  await expect(play).toBeVisible();
  await audit(page, info, 'artist-detail');
  await navigate(page, 'Genres');
  await page.getByRole('searchbox', { name: 'Search genres' }).fill('nonexistent');
  await expect(page.getByText('No genres match your search.', { exact: true })).toBeVisible();
  await page.getByRole('searchbox', { name: 'Search genres' }).fill('Ambient');
  await page.getByRole('link', { name: /^Ambient/ }).click();
  await expect(page).toHaveURL(/\/genres\/ambient$/);
  await expect(page.getByRole('heading', { name: 'Ambient', exact: true })).toBeVisible();
  await expect(page.getByRole('row', { name: /The Distant Sun/ })).toHaveCount(1);
  await expect(page.getByRole('row', { name: /Signal to Noise/ })).toHaveCount(1);
  await page.getByRole('button', { name: 'Play all', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Pause playback', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Pause playback', exact: true }).click();
  const playingTitle = await player.getByRole('button', { name: /^Open full screen player:/ }).getAttribute('aria-label');
  const genreTrackId = playingTitle?.includes('The Distant Sun') ? 'the-distant-sun' : 'signal-to-noise';
  await streams.complete(genreTrackId, player);
  await checkLayout(page);
  await audit(page, info, 'genre-detail');
  await navigate(page, 'Tracks');
  const search = page.getByRole('searchbox', { name: 'Search tracks' });
  await search.fill('absent track');
  await expect(page.getByText('No tracks found matching your search.', { exact: true })).toBeVisible();
  await search.fill('Scott');
  await expect(page.getByRole('row', { name: /The Distant Sun|Signal to Noise/ })).toHaveCount(2);
  await page.getByRole('combobox', { name: 'Sort tracks' }).selectOption('album');
  await expect(page.getByRole('combobox', { name: 'Sort tracks' })).toHaveValue('album');
  await audit(page, info, 'tracks-filtered');
  await checkAccessibility(page, info, 'tracks-filtered');
  await checkLayout(page);
  streams.assertClean(errors, { 'the-distant-sun': 1, ...(genreTrackId === 'signal-to-noise' ? { 'signal-to-noise': 1 } : {}) });
});

test('registration validates confirmation, creates a local account and signs out', async ({ page }, info) => {
  const errors = guard(page);
  await page.goto('/register');
  await page.getByLabel('Email', { exact: true }).fill('new-' + info.project.name + '@example.test');
  await page.getByLabel('Name', { exact: true }).fill('New listener');
  await page.getByLabel('Password', { exact: true }).fill('LocalMusicTest123!');
  await page.getByLabel('Confirm Password', { exact: true }).fill('DifferentPassword123!');
  await page.getByLabel('Access Code', { exact: true }).fill('e2e-access');
  await page.getByLabel('Password', { exact: true }).focus();
  await page.getByRole('button', { name: 'Show password', exact: true }).click();
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'text');
  await expect(page.getByLabel('Password', { exact: true })).toHaveValue('LocalMusicTest123!');
  await page.getByRole('button', { name: 'Hide password', exact: true }).click();
  await expect(page.getByLabel('Password', { exact: true })).toHaveAttribute('type', 'password');
  await expect(page.getByLabel('Password', { exact: true })).toHaveValue('LocalMusicTest123!');
  await page.getByRole('button', { name: 'Register', exact: true }).click();
  await expect(page.getByText('Passwords do not match', { exact: true })).toBeVisible();
  await page.getByLabel('Confirm Password', { exact: true }).fill('LocalMusicTest123!');
  await audit(page, info, 'registration-filled');
  await checkAccessibility(page, info, 'registration-filled');
  await page.getByRole('button', { name: 'Register', exact: true }).click();
  await expect(page).toHaveURL(/\/library$/);
  await expect(page.getByText('No albums in your library yet.', { exact: false })).toBeVisible();
  await audit(page, info, 'new-library');
  const toggle = page.getByRole('button', { name: 'Open navigation menu' });
  if (await toggle.isVisible()) await toggle.click();
  await page.getByRole('navigation', { name: 'Main navigation', exact: true }).getByRole('link', { name: 'Log out', exact: true }).click();
  await expect(page).toHaveURL(/\/$/);
  await page.goto('/library');
  await expect(page).toHaveURL(/\/login/);
  expect(errors).toEqual([]);
});
